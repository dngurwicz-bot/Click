/** מנרמל תווית שדה להשוואה — מסיר * ורווחים עודפים */
export function normalizeLabel(label: string): string {
  return label
    .replace(/\*/g, "")
    .replace(/\u00a0/g, " ")
    .replace(/\s+/g, " ")
    .replace(/\s*:\s*$/g, "")
    .trim();
}
